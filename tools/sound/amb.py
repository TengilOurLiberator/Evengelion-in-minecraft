"""amb.py - the eleven ambience beds.  Every bed is built from periodic ingredients (see dsp.py) so the file loops
with no audible join: noise is generated by FFT shaping, slow modulation is periodic, steady tones complete whole
cycles, and one-off events (bells, drips, alarms) are wrapped round the end."""
from dsp import *
from blocks import *
from reg import sound


def _rail_clack(r, f=1.0, w=1.0):
    y = modal([190 * f, 470 * f, 980 * f, 1700 * f, 2900 * f], [.09, .07, .05, .03, .02], [.6, 1, .7, .5, .3], 0.4, r, detune=15)
    y += 1.4 * w * fit(thump(0.15, 75, 45, 0.02, 0.05, 0.001), N(0.4))
    return y


@sound("amb.cicadas", lufs=-32, note="hot noon: ~40 resonator-driven cicada voices, slow chorus swells")
def cicadas(r):
    dur = 48.0
    n = N(dur)
    master = swell(n, r, 0.07, 1.6)                                  # the whole chorus swells and ebbs
    out = np.zeros((n, 2))
    for i in range(40):
        far = i >= 16
        fc = r.uniform(3600, 7400)
        pr = lockf(r.uniform(70, 190), dur)
        k = int(round(pr * dur))
        pos = (np.arange(k) + r.uniform(-0.35, 0.35, k)) / pr
        idx = np.round(pos * SR).astype(int) % n
        imp = np.zeros(n)
        np.add.at(imp, idx, r.uniform(0.5, 1.0, k))
        fcv = fc * (1 + 0.05 * drift(n, r, 0.4))
        if r.random() < 0.3:
            fcv = fc * (1 + 0.10 * lfo(n, int(r.integers(8, 20)), r.random()))
        y = csvf(imp, fcv, r.uniform(18, 40), "bp")
        on = 1 / (1 + np.exp(-5 * (drift(n, r, 0.12) - r.uniform(-0.5, 0.9))))
        am = on * master ** r.uniform(1.0, 1.8)
        if r.random() < 0.35:
            am = am * (0.55 + 0.45 * np.clip(lfo(n, int(r.integers(150, 400)), r.random()) * 3, -1, 1))
        y = y * am * (0.4 if far else 1.0) * r.uniform(0.5, 1.0)
        out += pan(y, r.uniform(-1, 1))
    out = rn(out, -24)
    wash = eq(stereo_noise(n, r, 0.0, hi=9000), [(1500, -40), (3500, -8), (5500, 0), (9000, -6), (14000, -30)])
    wash *= (swell(n, r, 0.1, 0.5) * (0.6 + 0.4 * np.clip(lfo(n, 2300, 0.2) * 2, -1, 1)))[:, None]
    heat = eq(stereo_noise(n, r, -3.0), [(25, -40), (120, -6), (400, 0), (900, -14), (3000, -30)]) * swell(n, r, 0.05, 0.4)[:, None]
    mix = out + rn(wash, -38) + rn(heat, -42)
    return eq(mix, [(60, -40), (300, -24), (1500, -12), (3000, 0), (8500, 0), (12000, -12), (16000, -26)])


@sound("amb.town_empty", lufs=-33, note="wind, singing wire, far crossing bell twice")
def town_empty(r):
    dur = 50.0
    n = N(dur)
    gust = swell(n, r, 0.09, 1.1)
    wind = stereo_noise(n, r, -3.0, corr=0.4)
    wind = eq(wind, [(25, -40), (80, -8), (220, 0), (600, -4), (1500, -13), (4000, -26), (9000, -40)])
    wind *= np.stack([gust ** 1.3, swell(n, r, 0.09, 1.1) ** 1.2 * 0.5 + 0.5 * gust ** 1.3], axis=1)
    whistle = csvf(white(n, r), 820 + 140 * drift(n, r, 0.3), 30, "bp") * gust ** 2.2
    t = T(n)
    hum = sum(a * np.sin(TWO_PI * lockf(f, dur) * t + i) for i, (f, a) in enumerate([(120, 1.0), (240, 0.45), (360, 0.2), (480, 0.08)]))
    hum = hum * (0.75 + 0.25 * swell(n, r, 0.2, 0.4))
    wire = np.sin(phase_of(lockf(1320, dur) + 3.0 * lfo(n, 6), True)) * gust ** 2.5
    bells = np.zeros(n)
    for t0, count in [(11.0, 9), (34.5, 7)]:
        for j in range(count):
            f = 1175 if j % 2 == 0 else 1318
            place(bells, bell(f, 1.8, r, tau=0.55, bright=0.8) * r.uniform(0.85, 1.0), t0 + j * 0.42, wrap=True)
    bells = lp(bells, 3200, 2)
    bells_st = cconv(bells, space("open")) * 0.7 + pan(bells, -0.4) * 0.3
    mix = rn(wind, -22) + pan(rn(whistle, -42), 0.2) + pan(rn(hum, -50), -0.1) + pan(rn(wire, -64), 0.3)
    mix = mix + bells_st * db(-22) / (np.max(np.abs(bells_st)) + 1e-9) * 0.6
    return mix


@sound("amb.car_interior", lufs=-32, note="closed car: 4-cyl engine tone, road, wind, joint thumps")
def car_interior(r):
    dur = 40.0
    n = N(dur)
    rpm = 2300 + 110 * drift(n, r, 0.12)
    eng = engine(dur, rpm, r, cyl=4, bright=0.3, rough=0.5, loop=True)
    eng = eq(eng, [(20, -8), (100, 0), (250, -6), (600, -17), (1500, -28), (4000, -40)])
    road = eq(stereo_noise(n, r, -3.0, corr=0.5), [(20, -30), (50, 0), (110, 2), (300, -8), (900, -20), (3000, -32)])
    road *= swell(n, r, 0.3, 0.4)[:, None]
    wind = eq(stereo_noise(n, r, 0.0, corr=0.3), [(100, -50), (500, -30), (1500, -16), (3500, -14), (8000, -30)])
    wind *= swell(n, r, 0.2, 0.5)[:, None]
    joints = np.zeros(n)
    t = 0.7
    while t < dur - 0.5:
        for off, g in [(0.0, 1.0), (0.11, 0.7)]:
            place(joints, thump(0.3, 100, 52, 0.02, 0.07, 0.002) * g * r.uniform(0.6, 1.0), t + off, wrap=True)
        t += r.uniform(1.8, 3.4)
    joints = eq(joints, [(20, -6), (140, 0), (300, -18), (1000, -40)])
    rattle = fold(ticks(dur + 1, r, 0.8, 1500, 4000, 0.003), n)
    mix = pan(rn(eng, -24), 0.0) * 1.0 + rn(road, -25) + rn(wind, -43) + pan(joints / (np.std(joints) + 1e-9) * db(-36), 0) + pan(rn(rattle, -50), 0.4)
    return mix


@sound("amb.tunnel", lufs=-31, note="rail wagon in a tunnel: rumble, rail-joint clacks in tunnel reverb, pressure whooshes")
def tunnel(r):
    dur = 40.0
    n = N(dur)
    rum = eq(stereo_noise(n, r, -6.0, corr=0.6), [(18, -20), (45, 0), (110, -2), (250, -10), (700, -22), (2500, -40)])
    rum *= swell(n, r, 0.25, 0.3)[:, None]
    roar = eq(stereo_noise(n, r, -3.0, corr=0.2), [(60, -40), (250, -8), (500, 0), (1200, -8), (3500, -24), (8000, -40)])
    clacks = np.zeros((n, 2))
    T0 = dur / 38
    for j in range(38):
        base = 0.37 + j * T0 + r.normal(0, 0.003)
        for off, g, side in [(0.0, 1.0, -0.5), (0.135, 0.8, 0.5), (0.55, 0.9, -0.5), (0.685, 0.7, 0.5)]:
            f = r.uniform(0.92, 1.08)
            place(clacks, _rail_clack(r, f), base + off + r.normal(0, 0.002), g * r.uniform(0.7, 1.0), side, wrap=True)
    clacks_r = cconv(clacks, space("tunnel"))
    clacks = clacks * 0.5 + clacks_r * 1.2
    puffs = np.zeros(n)
    for t0 in np.sort(r.uniform(2, dur - 4, 5)):
        pn = N(2.4)
        puff = bp(white(pn, r), 200, 900, 2) * np.sin(np.pi * np.arange(pn) / pn) ** 2
        place(puffs, puff, t0, wrap=True)
    mix = rn(rum, -18) + rn(roar, -38) + pan(rn(puffs, -36), 0) + rn(clacks, -23)
    return mix


@sound("amb.geofront", lufs=-33.5, note="vast airy quiet, distant water in a huge cavern, a few birds")
def geofront(r):
    dur = 56.0
    n = N(dur)
    air = eq(stereo_noise(n, r, -3.0, corr=0.0), [(20, -40), (100, -14), (400, -8), (1500, -14), (5000, -26), (12000, -40)])
    air *= swell(n, r, 0.05, 0.5)[:, None]
    wat = np.zeros((n, 2))
    for c in range(2):
        w = eq(white(n, r), [(150, -40), (500, -8), (1200, 0), (3000, -8), (7000, -30)])
        m = eq(white(n, r), [(2, 0), (20, 0), (60, -40)])
        m = np.clip(1 + 0.6 * m / (np.std(m) + 1e-9), 0, 3)
        wat[:, c] = w * m
    wat = cconv(wat, space("cavern")) * 1.0
    wat *= swell(n, r, 0.08, 0.5)[:, None]
    birds = np.zeros((n, 2))
    for t0 in [6.0, 17.5, 29.0, 38.5, 49.0]:
        ph = bird_phrase(r)
        place(birds, lp(ph, 7000, 2) * r.uniform(0.5, 1.0), t0 + r.uniform(-1, 1), pan=r.uniform(-0.8, 0.8), wrap=True)
    birds = birds * 0.35 + cconv(birds, space("cavern")) * 1.0
    sub = np.sin(TWO_PI * lockf(38, dur) * T(n)) * (0.6 + 0.4 * swell(n, r, 0.06, 0.5))
    return rn(air, -26) + rn(wat, -33) + rn(birds, -40) + pan(rn(sub, -44), 0)


@sound("amb.hq", lufs=-33, note="air handling, 60 Hz electrical hum, a faint high ballast pair, rare duct ticks")
def hq(r):
    dur = 40.0
    n = N(dur)
    air = eq(stereo_noise(n, r, -3.0, corr=0.1), [(20, -30), (60, -10), (150, 0), (400, -3), (900, -8), (2500, -20), (8000, -40)])
    comb = circ(lambda z: delayloop(z, SR / 190.0, 0.7, 0.4), white(n, r))
    comb = eq(comb, [(60, -30), (190, 0), (1500, -12), (5000, -40)])
    t = T(n)
    fan = np.sin(TWO_PI * lockf(341, dur) * t) * (0.7 + 0.3 * swell(n, r, 0.15, 0.3))
    hum = sum(a * np.sin(TWO_PI * lockf(f, dur) * t + i) for i, (f, a) in enumerate([(60, 1.0), (120, 0.6), (180, 0.25), (300, 0.08)]))
    ball = np.sin(TWO_PI * lockf(3910, dur) * t) + np.sin(TWO_PI * lockf(3910.5, dur) * t + 1)
    ticks_ = np.zeros(n)
    for t0 in [7.3, 19.8, 31.2]:
        place(ticks_, click(r, r.uniform(1800, 3200), 0.003, 0.05) * 1.0, t0, wrap=True)
    ticks_r = cconv(ticks_, space("corridor"), )
    return (rn(air, -26) + widen(rn(comb, -42), r, 0.8) + pan(rn(fan, -48), -0.2) + pan(rn(hum, -44), 0.1)
            + widen(rn(ball, -64), r, 0.9) + ticks_r * db(-40) / (np.max(np.abs(ticks_r)) + 1e-9))


def _drip(r, f0, level=1.0):
    n = N(0.4)
    t = T(n)
    f = f0 * (1 + 0.5 * (1 - np.exp(-t / 0.012)))
    y = np.sin(phase_of(f)) * np.exp(-t / 0.05) * np.minimum(1, t / 0.0015)
    y += 0.3 * np.sin(phase_of(f * 2.7)) * np.exp(-t / 0.015)
    y[:N(0.004)] += 0.4 * hp(white(N(0.004), r), 2500, 1)
    return level * y


@sound("amb.lake", lufs=-32, note="dark flooded chamber: drips in a wet hall, beating low hum, lapping water")
def lake(r):
    dur = 48.0
    n = N(dur)
    t = T(n)
    hum = sum(a * np.sin(TWO_PI * lockf(f, dur) * t + i) for i, (f, a) in
              enumerate([(54.0, 1.0), (54.25, 0.8), (81.5, 0.5), (109.0, 0.3), (109.5, 0.25), (163.0, 0.1)]))
    hum = hum * (0.6 + 0.4 * swell(n, r, 0.1, 0.8))
    lap = np.zeros((n, 2))
    for c in range(2):
        x = white(n, r)
        f = 450 + 220 * drift(n, r, 0.35)
        y = csvf(x, f, 1.4, "bp")
        ph_ = np.arange(n) / n
        c1 = 0.5 + 0.5 * np.sin(TWO_PI * int(r.integers(9, 13)) * ph_ + r.uniform(0, 6.28) + 2.2 * drift(n, r, 0.6))
        c2 = 0.5 + 0.5 * np.sin(TWO_PI * int(r.integers(17, 23)) * ph_ + r.uniform(0, 6.28) + 2.2 * drift(n, r, 0.6))
        cad = 0.6 * c1 + 0.4 * c2
        lap[:, c] = y * cad ** 2 * swell(n, r, 0.12, 1.0)
    bub = np.zeros(n)
    for _ in range(26):
        f0 = r.uniform(180, 420)
        bn = N(0.09)
        bt = T(bn)
        bub_ = np.sin(phase_of(f0 * (1 + 1.2 * bt / 0.09))) * np.exp(-bt / 0.03)
        place(bub, bub_ * r.uniform(0.3, 1), r.uniform(0, dur), wrap=True)
    drips = np.zeros((n, 2))
    for _ in range(15):
        place(drips, _drip(r, r.uniform(700, 1900)) * r.uniform(0.4, 1.0), r.uniform(0, dur), pan=r.uniform(-0.9, 0.9), wrap=True)
    drips = drips * 0.2 + cconv(drips, space("flooded")) * 1.0
    mix = pan(rn(hum, -30), 0.0) + rn(lap, -33) + pan(rn(bub, -52), 0.2) + rn(drips, -44)
    mix = eq(mix, [(18, -12), (60, 0), (500, -3), (1500, -12), (3500, -22), (9000, -40)])
    return mix


@sound("amb.cage", lufs=-33.5, note="enormous hangar: sub room tone, far coolant bubbling, thermal metal ticks")
def cage(r):
    dur = 60.0
    n = N(dur)
    t = T(n)
    sub = eq(stereo_noise(n, r, -6.0, corr=0.8), [(15, -12), (30, 0), (60, -3), (120, -20), (400, -40)])
    sub = sub * (0.7 + 0.3 * swell(n, r, 0.07, 0.8))[:, None]
    tone = np.sin(TWO_PI * lockf(41.2, dur) * t) + 0.4 * np.sin(TWO_PI * lockf(82.4, dur) * t + 1)
    tone *= 0.7 + 0.3 * swell(n, r, 0.05, 0.6)
    bub = np.zeros(n)
    t0 = 0.0
    while t0 < dur:
        t0 += r.exponential(2.2)
        for _ in range(int(r.integers(3, 12))):
            f0 = r.uniform(220, 800)
            bn = N(r.uniform(0.02, 0.05))
            bt = T(bn)
            b = np.sin(phase_of(f0 * (1 + 0.5 * bt / (bn / SR)))) * np.exp(-bt / (bn / SR / 3)) * np.minimum(1, bt / 0.002)
            place(bub, b * r.uniform(0.3, 1.0), t0 + r.uniform(0, 0.7), wrap=True)
    bub = lp(bub, 1300, 2)
    bub = cconv(bub, space("hangar", stereo=True))
    mt = np.zeros((n, 2))
    for _ in range(13):
        f = r.uniform(600, 3500)
        tk = modal([f, f * 2.3, f * 4.1], [.03, .02, .01], [1, .5, .25], 0.2, r, detune=20) * r.uniform(0.3, 1.0)
        place(mt, tk, r.uniform(0, dur), pan=r.uniform(-1, 1), wrap=True)
    for _ in range(3):
        cr = creak(r.uniform(0.6, 1.4), r, r.uniform(90, 160), r.uniform(70, 200), 0.5, 2.5) * 0.4
        place(mt, cr, r.uniform(0, dur), pan=r.uniform(-1, 1), wrap=True)
    mt = mt * 0.2 + cconv(mt, space("hangar")) * 1.0
    hush = eq(stereo_noise(n, r, -3.0, corr=0.2), [(30, -40), (200, -8), (800, 0), (3000, -10), (9000, -34)])
    return rn(sub, -26) + pan(rn(tone, -36), 0) + rn(bub, -48) + rn(mt, -44) + rn(hush, -40)


def _plug_bed(r, flooded):
    dur = 32.0
    n = N(dur)
    t = T(n)
    hush = eq(stereo_noise(n, r, -3.0, corr=0.5), [(20, -30), (100, -4), (300, 0), (800, -10), (2000, -26), (6000, -40)])
    mach = sum(a * np.sin(TWO_PI * lockf(f, dur) * t + i) for i, (f, a) in enumerate([(118, 1.0), (236, 0.5), (354, 0.2)]))
    mach *= 0.75 + 0.25 * swell(n, r, 0.15, 0.4)
    whine = np.sin(TWO_PI * lockf(3120, dur) * t) * (0.5 + 0.5 * swell(n, r, 0.2, 0.6))
    pulse = np.zeros(n)
    for k in range(32):                      # 1 Hz machine pulse
        place(pulse, thump(0.45, 56, 38, 0.05, 0.14, 0.006) * (1.0 if k % 4 else 1.15), 0.4 + k * 1.0 + r.normal(0, 0.004), wrap=True)
        place(pulse, lp(white(N(0.3), r), 260, 2) * expo(N(0.3), 0.06, 0.01) * 0.3, 0.4 + k * 1.0, wrap=True)
    airy = eq(stereo_noise(n, r, -3.0, corr=0.2), [(800, -60), (3000, -22), (8000, 0), (14000, -8)])    # a faint hiss floor (also hides codec edge noise at the loop join)
    if flooded:
        bub = np.zeros(n)
        for _ in range(60):
            f0 = r.uniform(90, 260)
            bn = N(0.12)
            bt = T(bn)
            place(bub, np.sin(phase_of(f0 * (1 + 1.5 * bt / 0.12))) * np.exp(-bt / 0.04) * r.uniform(0.2, 1), r.uniform(0, dur), wrap=True)
        mix = rn(lp_c(hush, 260), -28) + pan(rn(mach, -34), 0) + pan(rn(pulse, -24), 0) + pan(rn(bub, -44), 0.3)
        mix = eq(mix, [(18, -6), (60, 0), (200, -4), (400, -20), (1000, -40)]) + rn(airy, -56)
    else:
        mix = rn(hush, -29) + pan(rn(mach, -34), 0) + pan(rn(whine, -62), 0) + pan(rn(pulse, -27), 0) + rn(airy, -54)
        mix = eq(mix, [(18, -10), (60, 0), (300, 0), (800, -6), (1800, -18), (5000, -40)])
        mix = cconv(mix, space("capsule", True)) * 0.6 + mix * 0.4
    return mix


def lp_c(x, f):
    return eq(x, [(f * 0.5, 0), (f, -3), (f * 2, -24), (f * 4, -50)])


@sound("amb.plug", lufs=-33, note="sealed capsule: close, muffled, a 1 Hz machine pulse")
def plug(r):
    return _plug_bed(r, False)


@sound("amb.plug_flooded", lufs=-33, note="the same capsule filled: underwater-dull, bubbling, the same pulse")
def plug_flooded(r):
    return _plug_bed(np.random.default_rng(r.integers(1 << 30)), True)


@sound("amb.city_night", lufs=-32, note="wind between towers, canyon whistles, far two-tone and chirping alarms, one far thud")
def city_night(r):
    dur = 56.0
    n = N(dur)
    t = T(n)
    gust = swell(n, r, 0.1, 1.2)
    wind = eq(stereo_noise(n, r, -3.0, corr=0.3), [(30, -24), (100, -3), (300, 0), (800, -6), (2500, -20), (7000, -38)])
    wind *= np.stack([gust ** 1.4, (0.4 * swell(n, r, 0.1, 1.0) + 0.6 * gust) ** 1.4], axis=1)
    whs = np.stack([csvf(white(n, r), 640 + 180 * drift(n, r, 0.25), 25, "bp") * g for g in (gust ** 2.5, gust ** 2.0)], axis=1)
    hum = sum(a * np.sin(TWO_PI * lockf(f, dur) * t + i) for i, (f, a) in enumerate([(60, 1.0), (120, 0.5), (180, 0.3)]))
    hum *= 0.7 + 0.3 * swell(n, r, 0.1, 0.5)
    al = np.zeros(n)
    for t0, cnt in [(14.0, 17), (41.0, 15)]:                       # a far civil two-tone warble
        for j in range(cnt):
            f = 640 if j % 2 == 0 else 860
            sn = N(0.36)
            tone = (np.sin(TWO_PI * f * T(sn)) + 0.5 * np.sin(TWO_PI * 2 * f * T(sn)) + 0.33 * np.sin(TWO_PI * 3 * f * T(sn))) * np.minimum(1, np.minimum(T(sn) / 0.01, (0.36 - T(sn)) / 0.02))
            place(al, tone, t0 + j * 0.36, wrap=True)
    cal = np.zeros(n)
    for j in range(12):                                            # a far car alarm: repeated chirp-sweeps
        sn = N(0.28)
        tt = T(sn)
        f = 900 * (1500 / 900) ** (tt / 0.28)
        place(cal, np.sin(phase_of(f)) * np.sin(np.pi * tt / 0.28), 22.0 + j * 0.62, wrap=True)
    al = lp(al, 1700, 2)
    cal = lp(cal, 2200, 2)
    far = al * 1.0 + cal * 0.6
    far_st = cconv(far, space("city")) * 1.0 + pan(far, 0.1) * 0.15
    thud = np.zeros(n)
    place(thud, thump(1.5, 50, 28, 0.15, 0.5, 0.01), 33.0, wrap=True)
    place(thud, colored(N(3.0), r, -6, hi=100) * expo(N(3.0), 1.0, 0.05), 33.3, wrap=True)
    thud_st = cconv(thud, space("city"))
    return (rn(wind, -22) + rn(whs, -42) + pan(rn(hum, -50), 0.0) + far_st * db(-39) / (np.max(np.abs(far_st)) + 1e-9) * 2
            + thud_st * db(-24) / (np.max(np.abs(thud_st)) + 1e-9))

